it("preserves immutable meanings, separates opt-ins by version, and stores acknowledged selections", async () => {
  const user = await owner(), b = boardCommand(), r = id();
  expect(await store().list(user)).toEqual({ revision: 0, boards: [], routines: [], selectedBoardId: null, selectedRoutineId: null });
  await store().mutate(user, b);
  expect(await User.findById(user).lean()).not.toHaveProperty("styleMemory");
  await store().mutate(user, cmd("create_routine", 1, { id: r, label: "Class" }));
  await store().mutate(user, cmd("select_context", 2, { boardId: b.id, routineId: r }));
  expect(selectedStyleContext(await store().list(user))!.learningEnabled).toBe(false);
  await store().mutate(user, cmd("set_learning", 3, { boardId: b.id, profileVersion: 1, routineId: r, routineVersion: 1, enabled: true }));
  const selected = selectedStyleContext(await store().list(user))!;
  expect((await resolveStyleContext(user, selected)).compiled).toEqual(compiled);
  await store().mutate(user, cmd("rename_board", 4, { boardId: b.id, label: "School" }));
  await store().mutate(user, cmd("edit_board", 5, { boardId: b.id, rawSource: "Expressive", compiled: { ...compiled, aestheticKeywords: ["expressive"] } }));
  const state = await store().list(user);
  expect(state.boards[0]).toMatchObject({ label: "School", currentVersion: 2, versions: [{ version: 1, rawSource: b.rawSource, compiled }, { version: 2, rawSource: "Expressive" }] });
  expect(selectedStyleContext(state)!.learningEnabled).toBe(false);
  await expect(resolveStyleContext(user, selected)).rejects.toMatchObject({ code: "version_conflict" });
  expect((await resolveStyleContext(user, selected, { allowHistoricalVersions: true })).profileVersion).toBe(1);
  expect(await OutfitInteraction.countDocuments()).toBe(0);
});
it("replays lost acknowledgments without renewing revision and rejects changed operation payloads or stale commands", async () => {
  const user = await owner(), b = boardCommand(); let lost = true;
  const unreliable = new StyleMemoryStore({ afterWrite: async () => { if (lost) { lost = false; throw new Error("ack lost"); } } });
  await expect(unreliable.mutate(user, b)).rejects.toThrow("ack lost");
  expect((await store().mutate(user, b)).operation.revision).toBe(1);
  await store().mutate(user, cmd("rename_board", 1, { boardId: b.id, label: "Renamed" }));
  expect(await store().mutate(user, b)).toMatchObject({ operation: { revision: 1 }, state: { revision: 2, boards: [{ label: "Renamed" }] } });
  await expect(store().mutate(user, { ...b, label: "Changed" })).rejects.toMatchObject({ code: "operation_conflict" });
  await expect(store().mutate(user, boardCommand())).rejects.toMatchObject({ code: "revision_conflict" });
});
it("serializes duplicate retries and competing revisions, isolates owners and preserves archived historical sources", async () => {
  const user = await owner(), other = await owner(), b = boardCommand();
  expect((await Promise.all([store().mutate(user, b), store().mutate(user, b)])).map(row => row.operation.revision)).toEqual([1, 1]);
  await expect(store().mutate(other, cmd("rename_board", 0, { boardId: b.id, label: "Forged" }))).rejects.toMatchObject({ code: "board_unavailable" });
  const choices = await Promise.allSettled(["First", "Second"].map(label => store().mutate(user, cmd("rename_board", 1, { boardId: b.id, label }))));
  expect(choices.filter(row => row.status === "fulfilled")).toHaveLength(1);
  await store().mutate(user, cmd("select_context", 2, { boardId: b.id, routineId: null }));
  const selected = selectedStyleContext(await store().list(user))!;
  await store().mutate(user, cmd("archive_board", 3, { boardId: b.id }));
  expect((await store().list(user)).selectedBoardId).toBeNull();
  await expect(resolveStyleContext(user, selected)).rejects.toMatchObject({ code: "context_archived" });
  expect(contextIsVisible((await readStyleMemoryOwner(user)).data, selected)).toBe(true);
  await store().mutate(user, cmd("restore_board", 4, { boardId: b.id }));
  await store().mutate(user, cmd("erase_board", 5, { boardId: b.id }));
  expect(contextIsVisible((await readStyleMemoryOwner(user)).data, selected)).toBe(false);
  await expect(store().mutate(user, { ...b, operationId: randomUUID(), expectedRevision: 6 })).rejects.toMatchObject({ code: "identity_conflict" });
  expect((await store().list(other)).boards).toEqual([]);
});
it("tombstones before interrupted cleanup, purges captured content on retry, and keeps independent wear photo holds", async () => {
  const user = await owner(), other = await owner(), b = boardCommand(); await store().mutate(user, b);
  const snapshotId = new Types.ObjectId(), held = new Types.ObjectId(), unheld = new Types.ObjectId();
  const context = { boardId: b.id, profileId: b.profileId, profileVersion: 1, routineId: null, routineVersion: null, learningEnabled: false };
  await GenerationSnapshot.collection.insertOne({ _id: snapshotId, user: new Types.ObjectId(user), styleContext: { ...context, compiled }, itemSnapshots: [held, unheld].map(image => ({ evidence: { image: { imageRef: `mongo:${image}` } } })) });
  await GenerationSnapshot.collection.insertOne({ user: new Types.ObjectId(other), styleContext: context });
  await OutfitInteraction.collection.insertOne({ user: new Types.ObjectId(user), snapshotId, action: "accepted" });
  for (const image of [held, unheld]) await WardrobeImage.create({ _id: image, user, wardrobeItem: new Types.ObjectId(), base64: "aGVsbG8=", contentType: "image/png", sizeBytes: 5, snapshotRetained: true, ...(image === held ? { wearReferences: ["actual-wear"] } : {}) });
  const erase = cmd("erase_board", 1, { boardId: b.id });
  await expect(new StyleMemoryStore({ beforeCleanup: async () => { throw new Error("cleanup interrupted"); } }).mutate(user, erase)).rejects.toThrow("cleanup interrupted");
  const after = await readStyleMemoryOwner(user);
  expect(contextIsVisible(after.data, context)).toBe(false); expect(JSON.stringify(after.data)).not.toContain(b.rawSource);
  expect(await GenerationSnapshot.collection.countDocuments({ _id: snapshotId })).toBe(1);
  expect((await store().mutate(user, erase)).operation.revision).toBe(2);
  expect(await GenerationSnapshot.collection.countDocuments({ user: new Types.ObjectId(user) })).toBe(0);
  expect(await OutfitInteraction.countDocuments({ user })).toBe(0);
  expect(await GenerationSnapshot.collection.countDocuments({ user: new Types.ObjectId(other) })).toBe(1);
  expect(await WardrobeImage.exists({ _id: held })).not.toBeNull(); expect(await WardrobeImage.exists({ _id: unheld })).toBeNull();
  await cleanupStyleMemoryErasure(user);
});
