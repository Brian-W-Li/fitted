let harness: MongoHarness;
const id = () => String(new Types.ObjectId());
const compiled = { aestheticKeywords: ["relaxed", "clean"], palette: ["white", "navy"], patterns: [], fits: ["relaxed"] };
const boardCommand = (revision = 0) => ({ kind: "create_board", operationId: randomUUID(), expectedRevision: revision, id: id(), profileId: id(), label: "Campus", rawSource: "My campus direction", compiled });
const cmd = (kind: string, expectedRevision: number, extra: Record<string, unknown>) => ({ kind, expectedRevision, operationId: randomUUID(), ...extra });
async function owner() { return String((await User.create({ authId: randomUUID(), email: `${randomUUID()}@example.test` }))._id); }
const store = () => new StyleMemoryStore({ now: () => new Date("2026-11-10T12:00:00Z") });
