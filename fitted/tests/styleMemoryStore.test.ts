it("blocks delayed writes after account erasure and bounds receipts while retaining erasure capacity", async () => {
  const user = await owner(), b = boardCommand(), barrier = gate();
  const pending = new StyleMemoryStore({ beforeWrite: barrier.block }).mutate(user, b), failed = expect(pending).rejects.toMatchObject({ code: "account_unavailable" });
  await barrier.entered; await User.updateOne({ _id: user }, { $set: { erasureStarted: true } }); barrier.release(); await failed;
  expect((await User.collection.findOne({ _id: new Types.ObjectId(user) }))!.styleMemory).toBeUndefined();
  await User.deleteOne({ _id: user }); await expect(store().list(user)).rejects.toMatchObject({ code: "account_unavailable" });
  const next = await owner(); await store().mutate(next, b); const saved = await readStyleMemoryOwner(next);
  saved.data.operations = Array.from({ length: STYLE_MEMORY_NORMAL_RECEIPTS }, (_, n) => ({ id: randomUUID(), digest: String(n), revision: n }));
  await User.collection.updateOne({ _id: new Types.ObjectId(next) }, { $set: { styleMemory: saved.data } });
  await expect(store().mutate(next, cmd("rename_board", 1, { boardId: b.id, label: "Full" }))).rejects.toMatchObject({ code: "operation_limit" });
  expect((await store().mutate(next, cmd("erase_board", 1, { boardId: b.id }))).state.revision).toBe(2);
});
